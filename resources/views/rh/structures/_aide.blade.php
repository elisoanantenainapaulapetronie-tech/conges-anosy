<details class="aide-rh">
    <summary>Comprendre Type, Dépend de et Circuit de décision</summary>
    <div class="aide-rh__corps">
        <div>
            <h3>Type</h3>
            <p>La <strong>nature</strong> de la structure : Cabinet, Direction, Service, Service rattaché (directement au Chef de Région, comme la communication) ou Autre.
               Le type sert à reconnaître un <strong>directeur</strong> : est « directeur » le responsable d’une structure de type Direction.
               Si rien ne convient, choisissez « Autre » et précisez (Mission, Projet, Antenne…).</p>
        </div>
        <div>
            <h3>Dépend de</h3>
            <p>La structure <strong>placée juste au-dessus</strong> dans l’organigramme : un service dépend de sa direction, une direction du Secrétariat Général.
               C’est ce lien qui construit l’arbre, qui retrouve le <strong>responsable proposé</strong> pour l’avis (celui du service, sinon celui de la structure au-dessus)
               et qui rattache les agents à leur direction. Vide = niveau le plus haut.</p>
        </div>
        <div>
            <h3>Circuit de décision</h3>
            <p>L’<strong>autorité qui décide</strong> des demandes des agents de la structure. Trois choix :</p>
            <ul>
                <li><strong>Secrétaire Général</strong> : avis du responsable → contrôle RH → décision du SG.</li>
                <li><strong>Chef de Région</strong> : avis du responsable → contrôle RH → décision du Chef de Région.</li>
                <li><strong>Les deux</strong> : avis → contrôle RH → décision du SG, <em>puis</em> décision du Chef de Région. Si l’un refuse, la demande s’arrête.</li>
            </ul>
            <p>Le circuit de la structure est <em>proposé</em> dans la fiche de chaque agent ; la fiche reste la référence. Exceptions fixées par les règles : directeur demandeur,
               mission hors Région, absence d’un jour, maladie, maternité, paternité.</p>
        </div>
    </div>
</details>
